const L = SURF.left
const R = SURF.right
const F = SURF.floor
const tin = SURF.aboveTin
const V = SHOT_SPEED_KMH
const E = BOUNCE_RESTITUTION

/** Отражает 3D-событие по оси X: x → −x, боковая стена left↔right. */
function mirrorEvents(events) {
  return events.map((e) => {
    const m = { ...e }
    if (e.x != null) m.x = -e.x
    if (e.wall === 'left') m.wall = 'right'
    else if (e.wall === 'right') m.wall = 'left'
    return m
  })
}

/** Отражает SVG-путь по вертикальной оси корта (центр X=200): каждая пара x,y → 400−x,y. */
function mirrorPath(d) {
  return d.replace(
    /(-?\d+(?:\.\d+)?),(-?\d+(?:\.\d+)?)/g,
    (_, x, y) => `${400 - parseFloat(x)},${y}`,
  )
}

/**
 * Собирает удар из «левой» стороны и её зеркала.
 * left — { path (SVG), spec3d (events + физика), tip (подсказка) }
 * right — то же для правой; если не задан, берётся зеркало left.
 */
function symmetric({ left, right }) {
  const r = right ?? {}
  const leftPath = left.path
  const rightPath = r.path ?? mirrorPath(leftPath)
  const leftSpec = { side: 'left', ...left.spec3d }
  const rightSpec = {
    side: 'right',
    ...left.spec3d,
    ...(r.spec3d ?? {}),
    events: r.spec3d?.events ?? mirrorEvents(left.spec3d.events),
  }
  return {
    paths: [leftPath, rightPath],
    paths3d: [leftSpec, rightSpec],
    tooltips: [left.tip, r.tip ?? left.tip],
  }
}

