//   стекло снизу (y≈447), центр по X = 200. Схематичные, не метрические.
// paths3d — спецификации для Court3D (физика в lib/shotPhysics.js):
//   speedKmh — скорость удара; damping — потеря скорости на отскоке (резина 24 г, COR);
//   events с wall/floor дают точное касание (центр мяча = плоскость ± R).
//   После стекла мяч всегда идёт к передней стене (z уменьшается).
//
// Каждый удар авторится ОДНОЙ (левой) стороной, правая — точное зеркало по оси X:
//   mirrorEvents — отражает 3D-события (negate x, left↔right),
//   mirrorPath — отражает SVG-путь (x → 400 − x).
// Это гарантирует идеальную симметрию «слева/справа» без ручного дублирования чисел.

